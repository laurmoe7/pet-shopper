// Downloads the app's web fonts from Google Fonts into fonts/ and writes fonts.css (the @font-face rules), so the page serves them itself:
// no request to Google on every open (a GDPR matter in Europe), and they work offline from the first run. Only the Latin subsets are taken.
//   node tools/fetch-fonts.js
// Run it again after changing FAMILIES. The browser only downloads a font when text actually uses it, so the theme fonts cost nothing until worn.
const fs = require('fs');
const path = require('path');
const https = require('https');

const FAMILIES = ['Kiwi+Maru:wght@500', 'EB+Garamond:wght@400;500;600', 'Pixelify+Sans:wght@400;600', 'M+PLUS+Rounded+1c:wght@500;700;800'];
const SUBSETS = ['latin', 'latin-ext'];
// a browser's user agent gets woff2 files split by subset (unicode-range), the smallest form
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0 Safari/537.36';
const root = path.join(__dirname, '..');
const dir = path.join(root, 'fonts');

function get(url) {
  return new Promise((ok, fail) => {
    https.get(url, { headers: { 'User-Agent': UA } }, (res) => {
      if (res.statusCode !== 200) { fail(new Error(res.statusCode + ' ' + url)); return; }
      const parts = [];
      res.on('data', (d) => parts.push(d));
      res.on('end', () => ok(Buffer.concat(parts)));
    }).on('error', fail);
  });
}

(async () => {
  const css = (await get('https://fonts.googleapis.com/css2?family=' + FAMILIES.join('&family=') + '&display=swap')).toString();
  const blocks = [...css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([^}]*)\}/g)];
  fs.mkdirSync(dir, { recursive: true });
  const out = ['/* The app\'s fonts, served by the page itself (generated by tools/fetch-fonts.js; do not edit). */'];
  // a variable font (EB Garamond, Pixelify Sans) is one file for every weight: Google lists it once per weight with the same url, so the weights are joined into a range
  const fonts = new Map();
  for (const [, subset, body] of blocks) {
    if (!SUBSETS.includes(subset)) continue;
    const family = /font-family: '([^']+)'/.exec(body)[1], weight = Number(/font-weight: (\d+)/.exec(body)[1]), url = /url\((https:[^)]+\.woff2)\)/.exec(body)[1];
    const range = /unicode-range: ([^;]+);/.exec(body)[1];
    if (fonts.has(url)) fonts.get(url).weights.push(weight); else fonts.set(url, { family, subset, range, weights: [weight] });
  }
  let n = 0;
  for (const [url, f] of fonts) {
    const weights = f.weights.length > 1 ? Math.min(...f.weights) + '-' + Math.max(...f.weights) : String(f.weights[0]);
    const file = f.family.toLowerCase().replace(/[^a-z0-9]+/g, '-') + '-' + weights + '-' + f.subset + '.woff2';
    fs.writeFileSync(path.join(dir, file), await get(url));
    n++;
    out.push('@font-face { font-family: \'' + f.family + '\'; font-style: normal; font-weight: ' + weights.replace('-', ' ') + '; font-display: swap; src: url(fonts/' + file + ') format(\'woff2\'); unicode-range: ' + f.range + '; }');
  }
  fs.writeFileSync(path.join(root, 'fonts.css'), out.join('\n') + '\n');
  console.log('Saved ' + n + ' font files in fonts/ and wrote fonts.css');
})().catch((e) => { console.error(e.message); process.exit(1); });
